(() => {
    "use strict";
    const conversation = document.querySelector(".faq-conversation");
    const status = document.querySelector("[data-faq-status]");
    if (!conversation || !status || !window.fetch) return;
    const askForms = [...document.querySelectorAll("[data-faq-ask]")];
    const clearForm = document.querySelector("[data-faq-clear]");
    const handoff = document.querySelector("[data-faq-handoff]");
    const contact = document.querySelector("[data-faq-contact]");
    let busy = false;
    const node = (tag, text, className) => {
        const element = document.createElement(tag);
        if (text !== undefined) element.textContent = text;
        if (className) element.className = className;
        return element;
    };
    const updateHandoff = token => {
        if (!handoff) return;
        handoff.hidden = !token;
        handoff.querySelector('[name="handoffToken"]').value = token || "";
        handoff.querySelector('[name="confirmed"]').checked = false;
        if (contact) contact.hidden = !!token;
    };
    const renderTurn = turn => {
        conversation.querySelectorAll(".faq-empty").forEach(x => x.remove());
        if (!conversation.querySelector(".faq-turn")) conversation.replaceChildren();
        const article = node("article", undefined, "faq-turn");
        const question = node("p", undefined, "faq-user-question");
        question.append(node("strong", "You"), node("br"), document.createTextNode(turn.question));
        const answer = node("div", undefined, "faq-assistant-answer");
        answer.append(node("strong", turn.isAI ? "AI assistant" : "EduSmart support"), node("p", turn.answer));
        if (turn.needsHuman) answer.append(node("p", "A staff member can help with this question.", "faq-hint"));
        const sources = (turn.sources || []).filter(s => s.text.trim() !== turn.answer.trim());
        if (sources.length) {
            const details = node("details", undefined, "faq-sources");
            details.append(node("summary", `Website sources / records (${sources.length})`));
            const list = node("div", undefined, "faq-source-list");
            sources.forEach(source => {
                const item = node("div", undefined, "faq-source");
                item.append(node("strong", source.title), node("p", source.text));
                // Only same-origin relative links generated by the server are navigable.
                if (source.url && /^\/(?!\/)/.test(source.url) && !/[\\\u0000-\u0020]/.test(source.url)) {
                    const link = node("a", "View on website");
                    link.setAttribute("href", source.url);
                    item.append(link);
                }
                list.append(item);
            });
            details.append(list);
            answer.append(details);
        }
        article.append(question, answer);
        conversation.append(article);
        while (conversation.querySelectorAll(".faq-turn").length > 6) conversation.querySelector(".faq-turn").remove();
        // Scroll the conversation only; leave the document's scroll position alone.
        conversation.scrollTop = conversation.scrollHeight;
    };
    // Consume HTTP chunks as they arrive. This does not animate a completed JSON reply.
    const readStream = async response => {
        if (!response.body?.getReader) throw new Error("Streaming is unavailable in this browser.");
        const reader = response.body.getReader(), decoder = new TextDecoder();
        let buffer = "", final = null, draft = null, draftText = null;
        const handle = line => {
            if (!line.trim()) return;
            const event = JSON.parse(line);
            if (event.type === "start") {
                updateHandoff(null);
                conversation.querySelectorAll(".faq-empty").forEach(x => x.remove());
                draft = node("article", undefined, "faq-turn faq-stream-draft");
                const question = node("p", undefined, "faq-user-question");
                question.append(node("strong", "You"), node("br"), document.createTextNode(event.payload.question));
                draftText = node("p", "Preparing a response…");
                const answer = node("div", undefined, "faq-assistant-answer");
                answer.append(node("strong", "EduSmart support"), node("p", "Checking approved sources before displaying the response.", "faq-hint"), draftText);
                draft.append(question, answer); conversation.append(draft);
            } else if (event.type === "draft" && draftText) {
                draftText.textContent = event.payload.text || "Checking the response…";
                conversation.scrollTop = conversation.scrollHeight;
            } else if (event.type === "done") final = event.payload;
        };
        try {
            while (true) {
                const { value, done } = await reader.read();
                buffer += done ? decoder.decode() : decoder.decode(value, { stream:true });
                let split;
                while ((split=buffer.indexOf("\n"))>=0) { handle(buffer.slice(0,split)); buffer=buffer.slice(split+1); }
                if (buffer.length > 100000) throw new Error("Unexpected response size.");
                if(done)break;
            }
            if(buffer.trim())handle(buffer);
            if(!final)throw new Error("The response was interrupted. Please try again.");
            return final;
        } finally { draft?.remove(); reader.releaseLock(); }
    };
    const submit = async (event, clear) => {
        event.preventDefault();
        if (busy) return;
        const form = event.currentTarget;
        const data = new FormData(form);
        if (event.submitter?.name) data.set(event.submitter.name, event.submitter.value);
        busy = true;
        const controls = [...document.querySelectorAll("[data-faq-ask] button, [data-faq-clear] button, [data-faq-handoff] button")];
        const previous = controls.map(x => x.disabled);
        controls.forEach(x => { x.disabled = true; });
        conversation.setAttribute("aria-busy", "true");
        status.textContent = clear ? "Clearing conversation…" : "Getting your answer…";
        const controller = new AbortController();
        const timeout = window.setTimeout(() => controller.abort(), 45000);
        try {
            const response = await fetch(form.action, {
                method: "POST", body: data, credentials: "same-origin", cache: "no-store",
                headers: { "X-Requested-With": "XMLHttpRequest", "Accept": clear ? "application/json" : "application/x-ndjson, application/json" }, signal: controller.signal
            });
            if (response.status === 429) throw new Error("Too many questions. Please wait a minute and try again.");
            const kind = response.headers.get("content-type") || "";
            if (!kind.includes("application/json") && !kind.includes("application/x-ndjson"))
                throw new Error("Your session may have changed. Reload this page and try again.");
            const result = kind.includes("application/x-ndjson") && response.ok ? await readStream(response) : await response.json();
            if (!response.ok) throw new Error(result.error || "Unable to complete your request. Please try again.");
            if (clear) {
                if (!result.cleared) throw new Error("Unable to clear the conversation. Please try again.");
                conversation.replaceChildren(node("p", "Choose a question or ask one to get started.", "faq-hint faq-empty"));
                clearForm.hidden = true;
                updateHandoff(null);
            } else {
                if (!result.turn || typeof result.turn.question !== "string" || typeof result.turn.answer !== "string")
                    throw new Error("An unexpected response was received. Please try again.");
                renderTurn(result.turn);
                clearForm.hidden = false;
                updateHandoff(result.handoffToken);
                const input = form.querySelector('[name="Question"]');
                // Preserve any new text the user typed while waiting.
                if (input && input.value === data.get("Question")) input.value = "";
            }
            status.textContent = clear ? "Conversation cleared." : "Answer received.";
        } catch (error) {
            status.textContent = error.name === "AbortError"
                ? "The request took too long. Your question is still in the box; please try again."
                : (error instanceof TypeError ? "Connection failed. Your question is still in the box; please try again." : error.message);
        } finally {
            window.clearTimeout(timeout);
            busy = false;
            controls.forEach((x, i) => { x.disabled = previous[i]; });
            conversation.setAttribute("aria-busy", "false");
        }
    };
    askForms.forEach(form => form.addEventListener("submit", event => submit(event, false)));
    clearForm?.addEventListener("submit", event => submit(event, true));
    conversation.scrollTop = conversation.scrollHeight;
})();
